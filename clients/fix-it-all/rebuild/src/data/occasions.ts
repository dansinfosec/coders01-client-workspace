export interface OccasionPhoto {
  /** Pad in /public, bijv. "/assets/occasions/<slug>/<slug>-01.jpg". */
  src: string;
  /** Toegankelijke omschrijving. */
  alt: string;
}

export type Transmissie = "handgeschakeld" | "automaat";
export type BtwMarge = "marge" | "btw";

export interface Occasion {
  slug: string;
  status: OccasionStatus;
  merk: string;
  model: string;
  uitvoering: string;
  title: string;
  /** Verkoopprijs in hele euro's; null = op aanvraag. */
  prijs: number | null;
  bouwjaar: number;
  eersteToelating?: string;
  brandstof: string;
  /** null = niet gepubliceerd. */
  transmissie: Transmissie | null;
  versnellingen?: number;
  carrosserie: string;
  /** null = niet gepubliceerd (bijv. bij bedrijfswagens). */
  deuren: number | null;
  /** null = niet gepubliceerd. */
  zitplaatsen: number | null;
  /** Kilometerstand; null = niet vermeld / op aanvraag. */
  kmStand: number | null;
  cilinderinhoud: number | null;
  vermogenPk: number | null;
  vermogenKw: number | null;
  kenteken: string;
  kleur: string;
  interieur?: string;
  emissieklasse?: string;
  btwMarge: BtwMarge | null;
  airco?: boolean;
  highlights: string[];
  description: string;
  bijzonderheden?: string;
  photos: OccasionPhoto[];
  /** Opties/uitrusting (van de originele site; niet uit RDW). */
  opties?: string[];

  // --- RDW-verrijking (optioneel; ingevuld door lib/enrichOccasions.ts, nooit overschrijvend) ---
  /** APK-vervaldatum (DD-MM-YYYY). */
  apkVervaldatum?: string;
  voertuigsoort?: string;
  aantalCilinders?: number | null;
  co2Gecombineerd?: number | null;
  verbruikGecombineerd?: number | null;
  energielabel?: string;
  massaLedig?: number | null;
  toegestaneMaxMassa?: number | null;
  lengteCm?: number | null;
  breedteCm?: number | null;
  hoogteCm?: number | null;
  wielbasisCm?: number | null;
  /** Nieuwprijs volgens RDW (≠ verkoopprijs). */
  catalogusprijs?: number | null;
  /** Per aangevuld/afkomstig veld de bron. Alleen bijgehouden voor verrijkte velden. */
  sources?: Partial<Record<string, "site" | "rdw">>;
}

